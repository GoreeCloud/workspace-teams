import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import {createApplication} from '../src/server.mjs';
const ORIGIN='http://localhost:3000';
async function api(base,path,method='GET',data=null,cookie=null) {
  const response=await fetch(base+'/api'+path,{method,headers:{Origin:ORIGIN,'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},body:data?JSON.stringify(data):undefined});
  return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
}
test('owner export is private, space-scoped, bounded metadata without reusable credentials',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'workspace-export-test-'));
  const app=createApplication({dbPath:join(dir,'workspace.sqlite'),origin:ORIGIN});
  app.server.listen(0,'127.0.0.1');await once(app.server,'listening');
  t.after(async()=>{await new Promise(resolve=>app.server.close(resolve));app.close();rmSync(dir,{recursive:true,force:true});});
  const base='http://127.0.0.1:'+app.server.address().port;
  const owner=await api(base,'/bootstrap','POST',{username:'owner',password:'owner-strong-password-1234'});
  assert.equal(owner.status,201);
  const spaceId=(await api(base,'/spaces','GET',null,owner.cookie)).data.spaces[0].id;
  assert.equal((await api(base,'/spaces/'+spaceId+'/notes','POST',{title:'private title',body:'SPACE_ONE_SECRET_NOTE'},owner.cookie)).status,201);
  assert.equal((await api(base,'/spaces/'+spaceId+'/tasks','POST',{title:'Export task'},owner.cookie)).status,201);
  const secondary=await api(base,'/spaces','POST',{name:'Different space',kind:'personal'},owner.cookie);
  assert.equal(secondary.status,201);
  assert.equal((await api(base,'/spaces/'+secondary.data.id+'/notes','POST',{title:'hidden',body:'SPACE_TWO_SECRET_NOTE'},owner.cookie)).status,201);
  const invite=await api(base,'/spaces/'+spaceId+'/invites','POST',{},owner.cookie);
  assert.equal(invite.status,201);
  const member=await api(base,'/register','POST',{username:'member',password:'member-strong-password-1234',invite:invite.data.invite});
  assert.equal(member.status,201);
  const fileContent='ATTACHMENT_PRIVATE_CONTENT_404';
  const uploaded=await fetch(base+'/api/spaces/'+spaceId+'/files?name=private.txt',{method:'POST',headers:{Cookie:owner.cookie,Origin:ORIGIN,'Content-Type':'application/octet-stream'},body:fileContent});
  assert.equal(uploaded.status,201);
  const response=await fetch(base+'/api/spaces/'+spaceId+'/export',{headers:{Cookie:owner.cookie}});
  assert.equal(response.status,200);
  assert.equal(response.headers.get('cache-control'),'no-store');
  assert.match(response.headers.get('content-disposition'),/attachment/);
  const json=await response.json();
  assert.equal(json.schema,'goreecloud.workspace-teams.space.v1');
  assert.equal(json.space.id,spaceId);
  assert.equal(json.attachmentBytesIncluded,false);
  assert.equal(json.notes[0].body,'SPACE_ONE_SECRET_NOTE');
  assert.equal(json.tasks[0].title,'Export task');
  assert.equal(json.members.length,2);
  assert.equal(json.files.length,1);
  const raw=JSON.stringify(json);
  for(const secret of ['SPACE_TWO_SECRET_NOTE',fileContent,invite.data.invite,'password_hash','token_hash'])assert.equal(raw.includes(secret),false);
  assert.equal((await fetch(base+'/api/spaces/'+spaceId+'/export',{headers:{Cookie:member.cookie}})).status,403);
  assert.equal((await fetch(base+'/api/spaces/'+secondary.data.id+'/export',{headers:{Cookie:member.cookie}})).status,404);
  assert.equal((await fetch(base+'/api/spaces/'+spaceId+'/export')).status,401);
});
