import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import {createApplication} from '../src/server.mjs';
const origin='http://localhost:3000';
function fixture(t){
 const dir=mkdtempSync(join(tmpdir(),'goree-account-'));
 const app=createApplication({dbPath:join(dir,'workspace.sqlite'),origin});
 const ready=new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
 t.after(async()=>{await new Promise(resolve=>app.server.close(resolve));app.close();rmSync(dir,{recursive:true,force:true});});
 const call=async(path,method='GET',cookie=null,data=null,requestOrigin=origin)=>{
  await ready;const headers={};
  if(cookie)headers.Cookie=cookie;if(method!=='GET')headers.Origin=requestOrigin;
  if(data!==null)headers['Content-Type']='application/json';
  const response=await fetch('http://127.0.0.1:'+app.server.address().port+'/api'+path,{method,headers,body:data===null?undefined:JSON.stringify(data)});
  return {status:response.status,body:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};
 };
 return {app,ready,call};
}
test('password rotation revokes all existing sessions and preserves other accounts',async t=>{
 const {call}=fixture(t);
 const first=await call('/bootstrap','POST',null,{username:'owner',password:'initial-strong-password'});
 assert.equal(first.status,201);
 const second=await call('/login','POST',null,{username:'owner',password:'initial-strong-password'});
 assert.equal(second.status,200);
 assert.equal((await call('/account/security','GET',first.cookie)).body.activeSessions,2);
 assert.equal((await call('/account/security')).status,401);
 assert.equal((await call('/account/sessions/revoke-others','POST',first.cookie,null,'https://other.example')).status,403);
 assert.equal((await call('/account/security','GET',first.cookie)).body.activeSessions,2);
 const revoke=await call('/account/sessions/revoke-others','POST',first.cookie);
 assert.equal(revoke.body.revoked,1);
 assert.equal((await call('/spaces','GET',second.cookie)).status,401);
 const again=await call('/login','POST',null,{username:'owner',password:'initial-strong-password'});
 const space=(await call('/spaces','GET',first.cookie)).body.spaces[0];
 const invite=(await call('/spaces/'+space.id+'/invites','POST',first.cookie,{})).body.invite;
 const friend=await call('/register','POST',null,{username:'friend',password:'friend-strong-password',invite});
 assert.equal(friend.status,201);
 assert.equal((await call('/account/password','POST',first.cookie,{currentPassword:'wrong-password',newPassword:'different-password-123'})).status,403);
 assert.equal((await call('/account/password','POST',first.cookie,{currentPassword:'initial-strong-password',newPassword:'short'})).status,400);
 assert.equal((await call('/account/password','POST',first.cookie,{currentPassword:'initial-strong-password',newPassword:'initial-strong-password'})).status,400);
 const change=await call('/account/password','POST',first.cookie,{currentPassword:'initial-strong-password',newPassword:'different-password-123'});
 assert.equal(change.status,200);
 assert.match(change.cookie,/^gc_session=[A-Za-z0-9_-]{43}$/);
 assert.notEqual(change.cookie,first.cookie);
 assert.equal((await call('/spaces','GET',first.cookie)).status,401);
 assert.equal((await call('/spaces','GET',again.cookie)).status,401);
 assert.equal((await call('/account/security','GET',change.cookie)).body.activeSessions,1);
 assert.equal((await call('/login','POST',null,{username:'owner',password:'initial-strong-password'})).status,401);
 assert.equal((await call('/login','POST',null,{username:'owner',password:'different-password-123'})).status,200);
 assert.equal((await call('/spaces','GET',friend.cookie)).status,200);
});
